//! Generator for `oh.md`, the human documentation page of the ontology.
//!
//! `oh.md` is a pure function of `oh.ttl` (E16 no. 5e: Turtle master with
//! GENERATED docs). The binary regenerates it on every run and fails when
//! the committed file differs (doc-drift gate); `--write-doc` rewrites it.
//! Ordering is deterministic: sections by term kind, terms alphabetically.

use crate::model::{
    Model, OWL_ANNOTATION_PROPERTY, OWL_CLASS, OWL_DATATYPE_PROPERTY, OWL_OBJECT_PROPERTY,
    RDFS_DATATYPE,
};

/// Marker line; its presence tags the file as generated.
const HEADER: &str = "<!-- GENERATED by ontology/coverage from oh.ttl — do not edit by hand.\n     Regenerate: cargo run --manifest-path coverage/Cargo.toml -- --write-doc -->";

/// Generate the complete `oh.md` content from the model.
pub fn generate(model: &Model) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n");

    let title = model
        .header
        .label
        .as_deref()
        .unwrap_or("OpenHelvetia platform ontology");
    out.push_str(&format!("# {title}\n\n"));
    let version = model
        .header
        .version_info
        .as_deref()
        .unwrap_or("unversioned");
    let version_iri = model.header.version_iri.as_deref().unwrap_or("-");
    out.push_str(&format!(
        "**Version:** {version} · **Version IRI:** `{version_iri}` · **Namespace:** `https://ld.openhelvetia.swiss/schema/`\n\n"
    ));
    if let Some(comment) = &model.header.comment {
        out.push_str(&paragraphs(comment));
        out.push('\n');
    }

    if !model.header.imports.is_empty() {
        out.push_str("## Imported terms\n\n");
        out.push_str(
            "Foreign terms are referenced, never re-declared (see `imports/README.md` for the canonical specs):\n\n",
        );
        let mut by_prefix: std::collections::BTreeMap<String, Vec<String>> =
            std::collections::BTreeMap::new();
        for iri in &model.header.imports {
            let compact = model.compact(iri);
            let prefix = compact.split(':').next().unwrap_or("?").to_string();
            by_prefix.entry(prefix).or_default().push(compact);
        }
        for (prefix, mut terms) in by_prefix {
            terms.sort();
            out.push_str(&format!("- **{prefix}:** {}\n", terms.join(", ")));
        }
        out.push('\n');
    }

    let sections: [(&str, &str); 5] = [
        ("Classes", OWL_CLASS),
        ("Object properties", OWL_OBJECT_PROPERTY),
        ("Datatype properties", OWL_DATATYPE_PROPERTY),
        ("Annotation properties", OWL_ANNOTATION_PROPERTY),
        ("Value datatypes", RDFS_DATATYPE),
    ];
    for (heading, kind) in sections {
        let members: Vec<(&String, &crate::model::TermData)> = model
            .terms
            .iter()
            .filter(|(_, d)| d.kinds.contains(kind) && section_for(d) == kind)
            .collect();
        if members.is_empty() {
            continue;
        }
        out.push_str(&format!("## {heading}\n\n"));
        for (iri, data) in members {
            out.push_str(&format!("### {}\n\n", model.compact(iri)));
            if data.deprecated {
                out.push_str("**DEPRECATED** — kept with a transition period, never removed.\n\n");
            }
            if let Some(label) = &data.label {
                out.push_str(&format!("**{label}**"));
                if let Some(comment) = &data.comment {
                    out.push_str(&format!(" — {}", oneline(comment)));
                }
                out.push_str("\n\n");
            } else if let Some(comment) = &data.comment {
                out.push_str(&format!("{}\n\n", oneline(comment)));
            }
            let mut bullets: Vec<String> = Vec::new();
            push_links(&mut bullets, model, "Subclass of", &data.subclass_of);
            push_links(&mut bullets, model, "Subproperty of", &data.subproperty_of);
            push_links(&mut bullets, model, "Equivalent to", &data.equivalent);
            push_links(&mut bullets, model, "Domain", &data.domains);
            push_links(&mut bullets, model, "Range", &data.ranges);
            push_links(&mut bullets, model, "Disjoint with", &data.disjoint_with);
            push_links(&mut bullets, model, "See also", &data.see_also);
            for bullet in &bullets {
                out.push_str(&format!("- {bullet}\n"));
            }
            if !data.notes.is_empty() {
                out.push_str("- Notes:\n");
                for note in &data.notes {
                    out.push_str(&format!("  - {}\n", oneline(note)));
                }
            }
            if !bullets.is_empty() || !data.notes.is_empty() {
                out.push('\n');
            }
        }
    }
    out
}

/// Pick exactly one section per term so no term is documented twice
/// (priority order matches the doc's section order).
fn section_for(data: &crate::model::TermData) -> &'static str {
    for kind in [
        OWL_CLASS,
        OWL_OBJECT_PROPERTY,
        OWL_DATATYPE_PROPERTY,
        OWL_ANNOTATION_PROPERTY,
        RDFS_DATATYPE,
    ] {
        if data.kinds.contains(kind) {
            return kind;
        }
    }
    ""
}

fn push_links(bullets: &mut Vec<String>, model: &Model, label: &str, iris: &[String]) {
    if iris.is_empty() {
        return;
    }
    let rendered: Vec<String> = iris
        .iter()
        .map(|iri| format!("`{}`", model.compact(iri)))
        .collect();
    bullets.push(format!("{label}: {}", rendered.join(", ")));
}

/// Collapse a (possibly multi-line) literal into one normalized line.
fn oneline(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Normalize a literal but keep paragraph breaks (blank lines).
fn paragraphs(text: &str) -> String {
    text.split("\n\n")
        .map(oneline)
        .filter(|p| !p.is_empty())
        .collect::<Vec<_>>()
        .join("\n\n")
        + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{model, ttl};

    #[test]
    fn renders_deprecation_and_alignments() {
        let src = "@prefix oh: <https://ld.openhelvetia.swiss/schema/> .\n\
                   @prefix owl: <http://www.w3.org/2002/07/owl#> .\n\
                   @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n\
                   @prefix dcat: <http://www.w3.org/ns/dcat#> .\n\
                   <https://ld.openhelvetia.swiss/schema/> a owl:Ontology ; owl:versionInfo \"9.9.9\" .\n\
                   oh:Old a owl:Class ; rdfs:label \"old\"@en ; rdfs:subClassOf dcat:Dataset ; owl:deprecated true .\n";
        let doc = ttl::parse(src).expect("parse");
        let m = model::build(&doc).expect("model");
        let md = generate(&m);
        assert!(md.contains("GENERATED by ontology/coverage"));
        assert!(md.contains("**DEPRECATED**"), "{md}");
        assert!(md.contains("Subclass of: `dcat:Dataset`"), "{md}");
        assert!(md.contains("9.9.9"));
    }
}
